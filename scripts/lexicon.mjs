// Builds src/labs/speech/lexicon.ts: CMUdict pronunciations for just the words in the game's text.
// Usage: npm run lexicon. Downloads CMUdict once into node_modules/.cache/cmudict/ (never committed).
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const URL_DICT = 'https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict';
const cacheDir = join(root, 'node_modules/.cache/cmudict');
const cacheFile = join(cacheDir, 'cmudict.dict');

// Words phonemize.ts produces itself (numbers, abbreviations) must be in the lexicon too.
const EXTRA = `zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen
eighteen nineteen twenty thirty forty fifty sixty seventy eighty ninety hundred thousand and mister missus doctor saint
versus first second third fourth fifth sixth seventh eighth ninth tenth percent`.split(/\s+/);

const LITERAL = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\]|\\.)*)`/g;
function strings(src) {
  const out = [];
  for (const m of src.replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, '').matchAll(LITERAL)) {
    const raw = m[1] ?? m[2] ?? m[3] ?? '';
    out.push(raw.replace(/\\n/g, '\n').replace(/\\(.)/g, '$1').replace(/\$\{[^}]*\}/g, ' '));
  }
  return out;
}

function collect() {
  const texts = [];
  const cdir = join(root, 'src/content');
  for (const f of readdirSync(cdir)) {
    if (!f.endsWith('.ts') || f.endsWith('.test.ts') || f === 'fakeApi.ts') continue;
    texts.push(...strings(readFileSync(join(cdir, f), 'utf8')));
  }
  const ddir = join(root, 'src/world/dungeon/defs');
  for (const f of readdirSync(ddir)) {
    if (!f.endsWith('.ts')) continue;
    const src = readFileSync(join(ddir, f), 'utf8');
    texts.push(...strings([...src.matchAll(/\btext:\s*('(?:[^'\\\n]|\\.)*')/g)].map((m) => m[1]).join('\n')));
  }
  const words = new Set(EXTRA);
  for (const t of texts) {
    if (/^[\w-]+(\.[\w-]+)+$/.test(t)) continue; // ids like a.b
    const plain = t.replace(/\[(\/|\w+)\]/g, ' ').replace(/[‘’]/g, "'");
    for (const m of plain.matchAll(/[A-Za-z]+(?:'[A-Za-z]+)*/g)) words.add(m[0].toLowerCase());
  }
  return words;
}

async function dict() {
  if (!existsSync(cacheFile)) {
    mkdirSync(cacheDir, { recursive: true });
    const res = await fetch(URL_DICT);
    if (!res.ok) throw new Error(`CMUdict download failed: ${res.status}`);
    writeFileSync(cacheFile, await res.text());
  }
  const map = new Map();
  for (const line of readFileSync(cacheFile, 'utf8').split('\n')) {
    const sp = line.indexOf(' ');
    if (sp < 1) continue;
    const w = line.slice(0, sp);
    if (w.includes('(')) continue; // alternate variants: first only
    map.set(w.toLowerCase(), line.slice(sp + 1).replace(/\s*#.*$/, '').trim());
  }
  return map;
}

const words = collect();
const cmu = await dict();
const found = [];
const missing = [];
for (const w of [...words].sort()) {
  const p = cmu.get(w);
  if (p) found.push([w, p]);
  else missing.push(w);
}
const body = found.map(([w, p]) => `  ${JSON.stringify(w)}: ${JSON.stringify(p)},`).join('\n');
const out = `// Generated by npm run lexicon from CMUdict; never edit. Only the words in the game's text.
// CMUdict is BSD-licensed (c) Carnegie Mellon University (see CREDITS.md).
// "then" is a word here, not a promise hook.
/* eslint-disable unicorn/no-thenable */
export const LEXICON: Record<string, string> = {
${body}
};
`;
writeFileSync(join(root, 'src/labs/speech/lexicon.ts'), out);
console.log(`lexicon: ${found.length} entries, ${(out.length / 1024).toFixed(1)} KB`);
console.log(`missing from CMUdict (${missing.length}): ${missing.join(' ')}`);
