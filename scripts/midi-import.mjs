/**
 * npm run midi -- <folder> [--steps 2|4] [--out path]
 *
 * Reads the .mid files in assets/music-src/<folder>/ and writes src/core/imported/<folder>.ts:
 * the owner's notes in the game's music notation (melody lines, bass, chord names), ready for
 * an arrangement in src/core/tracks.ts to build on. The output is generated: never edit it,
 * re-export the MIDI and run this again. Prints what it found and anything it had to bend.
 *
 * Roles come from the file names: "chord" → chords, "bass" → bass, anything else → a melody
 * line (named after the file). Overlapping notes in one file become extra lines ("melody-2").
 * One file with several named tracks works too (the track names are checked the same way).
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseMidi } from '../src/core/midiFile.ts';
import { quantize, splitVoices, toLine, chordLine, noteName } from '../src/core/midiImport.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i < 0 ? fallback : args.splice(i, 2)[1];
};
const stepsPerBeat = Number(flag('steps', 2));
const outFlag = flag('out', null);
const folder = args[0];
if (!folder) {
  console.error('Usage: npm run midi -- <folder in assets/music-src> [--steps 2|4] [--out file.ts]');
  process.exit(1);
}
const dir = existsSync(folder) ? resolve(folder) : join(root, 'assets/music-src', folder);
const id = dir.split('/').filter(Boolean).pop();
const files = readdirSync(dir).filter((f) => /\.midi?$/i.test(f)).sort();
if (!files.length) {
  console.error(`No .mid files in ${dir}`);
  process.exit(1);
}

const slug = (s) => s.toLowerCase().replace(/\.midi?$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const roleOf = (label) => (/chord/i.test(label) ? 'chords' : /bass/i.test(label) ? 'bass' : 'melody');

// Gather every track that has notes: { label, role, notes } (beats).
const found = [];
const fileTempos = [];
let timeSig = [4, 4];
for (const f of files) {
  const midi = parseMidi(readFileSync(join(dir, f)));
  midi.tempos.forEach((t) => fileTempos.push(`${f}: ${t.bpm.toFixed(1)} bpm`));
  if (midi.timeSig) timeSig = midi.timeSig;
  const withNotes = midi.tracks.filter((t) => t.notes.length);
  for (const t of withNotes) {
    const base = slug(f);
    const label = withNotes.length > 1 && t.name ? `${base}-${slug(t.name)}` : base;
    const role = roleOf(withNotes.length > 1 ? `${f} ${t.name}` : f);
    found.push({ label, role, file: f, track: t.name, notes: t.notes });
  }
}
if (timeSig[1] !== 4) {
  console.error(`Time signature ${timeSig.join('/')} isn't supported yet (quarter-note beats only).`);
  process.exit(1);
}
const beatsPerBar = timeSig[0];
const stepsPerBar = beatsPerBar * stepsPerBeat;
const endBeat = Math.max(...found.flatMap((t) => t.notes.map((n) => n.beat + n.beats)));
const bars = Math.ceil(endBeat / beatsPerBar - 1e-6);

const lines = {};
const report = [];
const problems = [];
let chords = null;
for (const t of found) {
  const q = quantize(t.notes, stepsPerBeat);
  for (const o of q.offGrid) problems.push(`${t.label}: ${noteName(o.midi)} at beat ${o.beat.toFixed(3)} is ${Math.abs(o.error).toFixed(2)} step off the grid`);
  if (t.role === 'chords') {
    if (chords) problems.push(`${t.label}: a second chord track; only the first is used`);
    else {
      const c = chordLine(q.notes, bars, stepsPerBar);
      chords = c.line;
      problems.push(...c.problems.map((p) => `${t.label}: ${p}`));
      report.push(`${t.label}: chords, ${t.notes.length} notes`);
    }
    continue;
  }
  const voices = splitVoices(q.notes);
  voices.forEach((v, i) => {
    const name = i === 0 ? t.label : `${t.label}-${i + 1}`;
    lines[name] = toLine(v, bars, stepsPerBar);
    const first = Math.floor(v[0].step / stepsPerBar) + 1;
    report.push(`${name}: ${t.role}${voices.length > 1 ? ` (voice ${i + 1} of ${voices.length})` : ''}, ${v.length} notes, from bar ${first}, ${noteName(Math.min(...v.map((n) => n.midi)))}–${noteName(Math.max(...v.map((n) => n.midi)))}`);
  });
}
if (!chords) problems.push('no chord file found (name it with "chord" in it); the arrangement will need chords written by hand');

const q = (s) => JSON.stringify(s).replace(/"/g, "'");
const body = [
  `// GENERATED by \`npm run midi -- ${id}\` from assets/music-src/${id}/. Do not edit:`,
  '// re-export the MIDI and run it again. The arrangement lives in tracks.ts.',
  'export const midi = {',
  `  stepsPerBeat: ${stepsPerBeat},`,
  `  beatsPerBar: ${beatsPerBar},`,
  `  bars: ${bars},`,
  ...(chords ? [`  chords: ${q(chords)},`] : []),
  '  lines: {',
  ...Object.entries(lines).map(([k, v]) => `    ${q(k)}: ${q(v)},`),
  '  } as Record<string, string>,',
  '};',
  '',
].join('\n');
const outPath = outFlag ? resolve(outFlag) : join(root, 'src/core/imported', `${id}.ts`);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body);

console.log(`${id}: ${files.length} files, ${bars} bars of ${beatsPerBar}/4, ${stepsPerBeat} steps per beat`);
console.log(fileTempos.length ? `Tempo in the file(s): ${[...new Set(fileTempos)].join(', ')} (not imported; set bpm in tracks.ts)` : 'No tempo in the file(s): set bpm in the arrangement (tracks.ts)');
for (const r of report) console.log('  ' + r);
if (chords) console.log('  chords: ' + chords.split(' | ').reduce((runs, c) => (runs.at(-1)?.[0] === c ? (runs.at(-1)[1]++, runs) : [...runs, [c, 1]]), []).map(([c, n]) => (n > 1 ? `${c} ×${n}` : c)).join(', ') + ' (bars)');
console.log(problems.length ? `Problems (${problems.length}):\n` + problems.slice(0, 20).map((p) => '  - ' + p).join('\n') : 'No problems: everything sat on the grid.');
console.log('Wrote ' + outPath.replace(root + '/', ''));
